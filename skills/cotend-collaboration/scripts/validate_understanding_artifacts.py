def _orientation_section(text: str, language: str) -> tuple[dict[str, str], int]:
    labels = (
        ZH_LABELS if language == "zh-CN" else EN_LABELS if language == "en" else None
    )
    heading = (
        "这次在理解什么"
        if language == "zh-CN"
        else "What This Understanding Covers"
        if language == "en"
        else None
    )
    if labels is None or heading is None:
        raise ArtifactValidationError(
            "HUMAN_LANGUAGE", f"unsupported language: {language}"
        )
    headings = list(re.finditer(r"(?m)^##\s+(.+?)\s*$", text))
    if not headings or headings[0].group(1).strip() != heading:
        raise ArtifactValidationError(
            "HUMAN_ORIENTATION_ORDER", "orientation must be the first H2"
        )
    prelude_lines = [
        line.strip()
        for line in text[: headings[0].start()].lstrip("\ufeff").splitlines()
        if line.strip()
    ]
    if len(prelude_lines) > 1 or (
        prelude_lines and not re.fullmatch(r"#\s+\S.*", prelude_lines[0])
    ):
        raise ArtifactValidationError(
            "HUMAN_ORIENTATION_ORDER",
            "only an optional H1 title may precede orientation",
        )
    start = headings[0].end()
    end = headings[1].start() if len(headings) > 1 else len(text)
    section = text[start:end]
    if "```" in section or re.search(r"(?m)^\s*\|", section):
        raise ArtifactValidationError(
            "HUMAN_ORIENTATION_FORMAT", "orientation contains table/code"
        )
    result: dict[str, str] = {}
    order: list[str] = []
    current_label: str | None = None
    current_lines: list[str] = []

    def finish_field() -> None:
        nonlocal current_label, current_lines
        if current_label is None:
            return
        value = "\n".join(line for line in current_lines if line).strip()
        if not value:
            raise ArtifactValidationError(
                "HUMAN_ORIENTATION_FIELD", f"empty field: {current_label}"
            )
        result[current_label] = value
        current_label = None
        current_lines = []

    for line in section.splitlines():
        match = re.match(r"^\s*-\s*\*\*(.+?)\s*[:：]\*\*\s*(.*?)\s*$", line)
        if match:
            label, value = match.group(1).strip(), match.group(2).strip()
            if label in labels:
                if label in result or label == current_label:
                    raise ArtifactValidationError(
                        "HUMAN_ORIENTATION_FIELD", f"duplicate field: {label}"
                    )
                finish_field()
                current_label = label
                current_lines = [value] if value else []
                order.append(label)
                continue
        if current_label is not None and line.strip():
            current_lines.append(line.strip())
    finish_field()
    if tuple(order) != labels:
        raise ArtifactValidationError(
            "HUMAN_ORIENTATION_FIELD", f"expected {labels}, got {tuple(order)}"
        )
    if re.fullmatch(r"(?:N|NODE|UE)[-_]?\w+", result[labels[0]], flags=re.IGNORECASE):
        raise ArtifactValidationError(
            "HUMAN_ORIENTATION_FIELD", "subject is only an identifier"
        )
    return result, headings[0].start()


def _contains_any(text: str, markers: tuple[str, ...]) -> bool:
    normalized = _nfc(text).casefold()
    return any(_nfc(marker).casefold() in normalized for marker in markers)


def _ref_pattern(value: str) -> str:
    escaped = re.escape(_nfc(value).casefold())
    if re.fullmatch(r"[0-9A-Za-z_-]+", value):
        return rf"(?<![0-9a-z_-]){escaped}(?![0-9a-z_-])"
    return escaped


def _contains_in_order(text: str, items: tuple[str, ...]) -> bool:
    normalized = _nfc(text).casefold()
    cursor = 0
    for item in items:
        match = re.search(_ref_pattern(item), normalized[cursor:])
        if match is None:
            return False
        cursor += match.end()
    return True


def _contains_negated_marker(
    text: str, markers: tuple[str, ...], language: str
) -> bool:
    prefixes = (
        (r"不是", r"并不是", r"并非")
        if language == "zh-CN"
        else (r"not(?:\s+the)?", r"is\s+not", r"isn't")
    )
    normalized = _nfc(text).casefold()
    for marker in markers:
        escaped = re.escape(_nfc(marker).casefold())
        for prefix in prefixes:
            pattern = rf"{prefix}\s*[:：]?\s*(?:状态为\s*)?{escaped}"
            if re.search(pattern, normalized):
                return True
    return False


def _fact_segments(text: str) -> list[str]:
    return [
        segment.strip()
        for segment in re.split(r"[；;。.!?！？\r\n]+", _nfc(text))
        if segment.strip()
    ]


def _matching_fact_segment(
    segments: list[str], required: tuple[str, ...], markers: tuple[str, ...]
) -> str | None:
    for segment in segments:
        normalized = segment.casefold()
        if all(re.search(_ref_pattern(item), normalized) for item in required) and any(
            _nfc(marker).casefold() in normalized for marker in markers
        ):
            return segment
    return None


def _validate_human_project_position(
    labels: dict[str, str], language: str, navigation: dict[str, Any]
) -> None:
    label = "项目位置" if language == "zh-CN" else "Project position"
    position = _nfc(labels[label])
    segments = _fact_segments(position)
    route_markers = (
        ("当前路线", "活动路线")
        if language == "zh-CN"
        else ("current route", "active route")
    )
    route_segment = _matching_fact_segment(
        segments, tuple(navigation["active_path"]), route_markers
    )
    route_unknown_markers = (
        ("路线未知", "当前路线未知")
        if language == "zh-CN"
        else ("route unknown", "current route unknown")
    )
    if route_segment is None or (
        not navigation["active_path"]
        and not _contains_any(route_segment, route_unknown_markers)
    ):
        raise ArtifactValidationError(
            "HUMAN_PROJECT_POSITION_MISMATCH",
            "project position omits one local current-route statement",
        )
    route_negations = (
        ("当前路线不是", "并非当前路线", "不再是当前路线")
        if language == "zh-CN"
        else ("current route is not", "not the current route")
    )
    if _contains_any(route_segment, route_negations) or not _contains_in_order(
        route_segment, tuple(navigation["active_path"])
    ):
        raise ArtifactValidationError(
            "HUMAN_PROJECT_POSITION_MISMATCH",
            "project position negates or reorders the frozen active route",
        )

    boundary = navigation["reliable_boundary"]
    first_invalid = boundary["first_invalid_or_unverified_ref"]
    first_state = boundary["first_invalid_or_unverified_state"]
    if first_invalid is None:
        boundary_markers = (
            ("可靠边界未知", "未核验点未知", "边界未知")
            if language == "zh-CN"
            else ("reliable boundary unknown", "unverified point unknown")
        )
        boundary_segment = _matching_fact_segment(segments, (), boundary_markers)
        if boundary_segment is None:
            raise ArtifactValidationError(
                "HUMAN_PROJECT_POSITION_MISMATCH",
                "project position omits the explicitly unknown reliable boundary",
            )
    else:
        state_markers = {
            "partial": ("partial", "部分完成", "部分有效"),
            "blocked": ("blocked", "阻断", "受阻"),
            "unverified": ("unverified", "未验证", "未核验"),
            "unknown": ("unknown", "未知"),
        }[first_state]
        boundary_markers = (
            ("首个未闭合点", "首个未核验点", "首个未验证点")
            if language == "zh-CN"
            else ("first unclosed point", "first unverified point")
        )
        boundary_segment = _matching_fact_segment(
            segments, (first_invalid,), boundary_markers
        )
        if (
            boundary_segment is None
            or not _contains_any(boundary_segment, state_markers)
            or _contains_negated_marker(boundary_segment, state_markers, language)
        ):
            raise ArtifactValidationError(
                "HUMAN_PROJECT_POSITION_MISMATCH",
                "project position omits one local boundary ref/state statement",
            )

    next_leaf = navigation["current_next_leaf_ref"]
    if next_leaf is None:
        next_markers = (
            ("尚未选择", "未选择", "未确定")
            if language == "zh-CN"
            else ("not selected", "no next leaf")
        )
        next_labels = (
            ("下一开发叶", "下一叶")
            if language == "zh-CN"
            else ("next development leaf", "next leaf")
        )
        next_segment = _matching_fact_segment(segments, (), next_labels)
        if (
            next_segment is None
            or not _contains_any(next_segment, next_markers)
            or _contains_negated_marker(next_segment, next_markers, language)
            or _contains_any(
                next_segment,
                ("已经选择", "已选择")
                if language == "zh-CN"
                else ("already selected",),
            )
        ):
            raise ArtifactValidationError(
                "HUMAN_PROJECT_POSITION_MISMATCH",
                "project position omits the explicit no-next-leaf state",
            )
    else:
        next_labels = (
            ("下一开发叶", "下一叶")
            if language == "zh-CN"
            else ("next development leaf", "next leaf")
        )
        next_segment = _matching_fact_segment(segments, (next_leaf,), next_labels)
        if next_segment is None or _contains_negated_marker(
            next_segment, (next_leaf,), language
        ):
            raise ArtifactValidationError(
                "HUMAN_PROJECT_POSITION_MISMATCH",
                "project position omits one local selected-next-leaf statement",
            )

    relation_markers = {
        "active_node": (
            ("当前节点", "活动节点")
            if language == "zh-CN"
            else ("active node",)
        ),
        "active_path_ancestor": (
            ("上游", "祖先")
            if language == "zh-CN"
            else ("active-path ancestor", "upstream")
        ),
        "active_path_descendant": (
            ("下游", "后继")
            if language == "zh-CN"
            else ("active-path descendant", "downstream")
        ),
        "inactive_sibling": (
            ("非活动同级", "非当前同级", "路线外同级")
            if language == "zh-CN"
            else ("inactive sibling", "off-route sibling")
        ),
        "outside_current_route": (
            ("当前路线之外", "不在当前路线")
            if language == "zh-CN"
            else ("outside the current route",)
        ),
        "unknown": (
            ("关系未知",) if language == "zh-CN" else ("relation unknown",)
        ),
    }
    for relation in navigation["subject_route_relations"]:
        subject_ref = relation["subject_ref"]
        markers = relation_markers[relation["relation"]]
        relation_segment = _matching_fact_segment(
            segments,
            (subject_ref,),
            markers,
        )
        if relation_segment is None or _contains_negated_marker(
            relation_segment, markers, language
        ):
            raise ArtifactValidationError(
                "HUMAN_PROJECT_POSITION_MISMATCH",
                f"project position omits subject relation: {subject_ref}",
            )


def _validate_receipt_common(
    receipt: dict[str, Any],
    ai: dict[str, Any] | None,
    fields: set[str],
    schema: str,
) -> None:
    if set(receipt) != fields:
        missing = sorted(fields - set(receipt))
        extra = sorted(set(receipt) - fields)
        raise ArtifactValidationError(
            "RECEIPT_SCHEMA", f"missing={missing}, extra={extra}"
        )
    if receipt["receipt_schema"] != schema:
        raise ArtifactValidationError("RECEIPT_SCHEMA", "unsupported receipt_schema")
    _nonempty(
        receipt["understanding_entity_id"],
        "RECEIPT_FIELD",
        "understanding_entity_id",
    )
    _nonempty(receipt["revision_id"], "RECEIPT_FIELD", "revision_id")
    if ai is not None:
        ai_entity_id = (
            ai["understanding_entity"]["entity_id"]
            if ai.get("contract_schema") in {AI_SCHEMA_V3, AI_SCHEMA}
            else ai["understanding_entity_id"]
        )
        if (
            receipt["understanding_entity_id"] != ai_entity_id
            or receipt["revision_id"] != ai["revision_id"]
        ):
            raise ArtifactValidationError(
                "BINDING_ENTITY_REVISION", "receipt and AI entity/revision differ"
            )
    if receipt["language"] not in {"zh-CN", "en"}:
        raise ArtifactValidationError("RECEIPT_FIELD", "language unsupported")
    if (
        not isinstance(receipt["repair_attempts"], int)
        or isinstance(receipt["repair_attempts"], bool)
        or receipt["repair_attempts"] not in {0, 1}
    ):
        raise ArtifactValidationError(
            "REPAIR_BUDGET_EXCEEDED", "repair_attempts must be 0 or 1"
        )
    if receipt["reported_status"] not in {"generated", "repaired"}:
        raise ArtifactValidationError("RECEIPT_FIELD", "reported_status unsupported")
    refs = _assert_projection_refs(
        receipt["projection_refs"], "RECEIPT_PROJECTION_REFS"
    )
    if ai is not None and refs != ai["projection_refs"]:
        raise ArtifactValidationError(
            "BINDING_REFS", "receipt and AI projection refs differ"
        )
    hashes = receipt["projection_sha256"]
    if (
        not isinstance(hashes, dict)
        or set(hashes) != RECEIPT_HASH_FIELDS
        or not isinstance(hashes["evidence_appendix_refs"], dict)
    ):
        raise ArtifactValidationError(
            "RECEIPT_HASH_SCHEMA", "projection_sha256 has wrong shape"
        )
    for value in (hashes["human_brief_ref"], hashes["ai_working_contract_ref"]):
        if not isinstance(value, str) or not SHA256_RE.fullmatch(value):
            raise ArtifactValidationError(
                "RECEIPT_HASH_SCHEMA", "invalid projection sha256"
            )
    evidence_refs = refs["evidence_appendix_refs"]
    if set(hashes["evidence_appendix_refs"]) != set(evidence_refs):
        raise ArtifactValidationError(
            "RECEIPT_HASH_SCHEMA", "evidence hash refs differ"
        )
    for value in hashes["evidence_appendix_refs"].values():
        if not isinstance(value, str) or not SHA256_RE.fullmatch(value):
            raise ArtifactValidationError(
                "RECEIPT_HASH_SCHEMA", "invalid evidence sha256"
            )
    owners = receipt["owner_reads"]
    if not isinstance(owners, dict) or set(owners) != {
        "project_intelligence",
        "plan_tree",
    }:
        raise ArtifactValidationError(
            "OWNER_READ_MISSING", "both understanding owners are required"
        )
    for key in owners:
        item = owners[key]
        if (
            not isinstance(item, dict)
            or set(item) != {"ref", "sha256"}
            or not isinstance(item["sha256"], str)
            or not SHA256_RE.fullmatch(item["sha256"])
        ):
            raise ArtifactValidationError(
                "OWNER_READ_MISSING", f"invalid owner read: {key}"
            )
        _nonempty(item["ref"], "OWNER_READ_MISSING", f"{key}.ref")
    if (
        owners["project_intelligence"]["ref"].replace("\\", "/")
        != "project-intelligence.md"
    ):
        raise ArtifactValidationError(
            "OWNER_READ_MISSING", "project intelligence ref missing"
        )
    if owners["plan_tree"]["ref"].replace("\\", "/") != "plan-tree.md":
        raise ArtifactValidationError("OWNER_READ_MISSING", "plan tree ref missing")
    for name in _walk_names(receipt):
        if name in FORBIDDEN_NAMES:
            raise ArtifactValidationError(
                "PROJECTION_CANONICAL_LABEL_FORBIDDEN",
                f"forbidden receipt field: {name}",
            )
    serialized = json.dumps(receipt, ensure_ascii=False)
    if any(label in serialized for label in FORBIDDEN_LABELS):
        raise ArtifactValidationError(
            "PROJECTION_CANONICAL_LABEL_FORBIDDEN", "canonical projection label"
        )


def _validate_receipt(receipt: dict[str, Any], ai: dict[str, Any] | None) -> str:
    """Validate historical v1-v3 receipts or the current v4 successor."""
    schema = receipt.get("receipt_schema")
    if schema == RECEIPT_SCHEMA_V1:
        _validate_receipt_common(receipt, ai, RECEIPT_FIELDS_V1, RECEIPT_SCHEMA_V1)
        if receipt["profile"] not in {"Full", "Adaptive"}:
            raise ArtifactValidationError(
                "RECEIPT_FIELD", "legacy profile must be Full or Adaptive"
            )
        if ai is not None and ai.get("contract_schema") != AI_SCHEMA_V1:
            raise ArtifactValidationError(
                "SCHEMA_COMPATIBILITY",
                "legacy receipt must bind the historical AI contract",
            )
        return RECEIPT_SCHEMA_V1
    if schema == RECEIPT_SCHEMA_V2:
        _validate_receipt_common(receipt, ai, RECEIPT_FIELDS_V2, RECEIPT_SCHEMA_V2)
        profile = receipt.get("runtime_profile")
        source = receipt.get("runtime_profile_source")
        if profile not in RUNTIME_PROFILES:
            raise ArtifactValidationError(
                "PROFILE_FIELD", "runtime_profile must be full or adaptive"
            )
        if source not in RUNTIME_PROFILE_SOURCES:
            raise ArtifactValidationError(
                "PROFILE_SOURCE",
                "runtime_profile_source is required and must be sourced",
            )
        if ai is not None:
            if ai.get("contract_schema") != AI_SCHEMA_V2:
                raise ArtifactValidationError(
                    "SCHEMA_COMPATIBILITY",
                    "v2 receipt requires the historical v2 AI contract",
                )
            if profile != ai.get("runtime_profile") or source != ai.get(
                "runtime_profile_source"
            ):
                raise ArtifactValidationError(
                    "PROFILE_BINDING_MISMATCH",
                    "receipt and AI runtime profile/source differ",
                )
        return RECEIPT_SCHEMA_V2
    if schema == RECEIPT_SCHEMA_V3:
        expected_ai_schema = AI_SCHEMA_V3
        receipt_fields = RECEIPT_FIELDS_V3
    elif schema == RECEIPT_SCHEMA:
        expected_ai_schema = AI_SCHEMA
        receipt_fields = RECEIPT_FIELDS_V4
    else:
        raise ArtifactValidationError("RECEIPT_SCHEMA", "unsupported receipt_schema")
    _validate_receipt_common(receipt, ai, receipt_fields, schema)
    profile = receipt.get("runtime_profile")
    source = receipt.get("runtime_profile_source")
    if profile not in RUNTIME_PROFILES:
        raise ArtifactValidationError(
            "PROFILE_FIELD", "runtime_profile must be full or adaptive"
        )
    if source not in RUNTIME_PROFILE_SOURCES:
        raise ArtifactValidationError(
            "PROFILE_SOURCE", "runtime_profile_source is required and must be sourced"
        )
    if ai is not None:
        if ai.get("contract_schema") != expected_ai_schema:
            raise ArtifactValidationError(
                "SCHEMA_COMPATIBILITY",
                f"{schema} requires {expected_ai_schema}",
            )
        if profile != ai.get("runtime_profile") or source != ai.get(
            "runtime_profile_source"
        ):
            raise ArtifactValidationError(
                "PROFILE_BINDING_MISMATCH",
                "receipt and AI runtime profile/source differ",
            )
        if receipt["artifact_producer_id"] != ai.get("artifact_producer_id"):
            raise ArtifactValidationError(
                "PRODUCER_BINDING_MISMATCH", "receipt and AI producer differ"
            )
    _nonempty(
        receipt["artifact_producer_id"],
        "RECEIPT_FIELD",
        "artifact_producer_id",
    )
    context_binding = receipt["generation_context"]
    if not isinstance(context_binding, dict) or set(context_binding) != {
        "context_id",
        "sha256",
    }:
        raise ArtifactValidationError(
            "GENERATION_CONTEXT_BINDING", "generation_context binding has wrong fields"
        )
    _nonempty(
        context_binding["context_id"],
        "GENERATION_CONTEXT_BINDING",
        "context_id",
    )
    if not isinstance(context_binding["sha256"], str) or not SHA256_RE.fullmatch(
        context_binding["sha256"]
    ):
        raise ArtifactValidationError(
            "GENERATION_CONTEXT_BINDING", "generation context hash is invalid"
        )
    return schema


def validate_artifacts(
    artifact_root: Path,
    owner_root: Path,
    receipt_ref: str = "CANARY-FINAL-RECEIPT.json",
    *,
    project_root: Path | None = None,
    expected_context: dict[str, Any] | None = None,
    generation_context_path: Path | None = None,
    expected_generation_context_sha256: str | None = None,
) -> dict[str, Any]:
    """Validate a generated artifact set and return a deterministic report."""
    root = artifact_root.resolve(strict=True)
    receipt_path = _safe_resolve(root, receipt_ref, "REF_UNSAFE")
    receipt = _load_json(receipt_path)
    receipt_schema = _validate_receipt(receipt, None)
    ai_path = _safe_resolve(
        root, receipt["projection_refs"]["ai_working_contract_ref"], "REF_UNSAFE"
    )
    human_path = _safe_resolve(
        root, receipt["projection_refs"]["human_brief_ref"], "REF_UNSAFE"
    )
    evidence_paths = [
        _safe_resolve(root, ref, "REF_UNSAFE")
        for ref in receipt["projection_refs"]["evidence_appendix_refs"]
    ]
    ai = _load_json(ai_path)
    ai_schema = _validate_ai(ai)
    _validate_receipt(receipt, ai)
    generation_context_validated = False
    project_route_reads_validated = False
    generation_context: dict[str, Any] | None = None
    if ai_schema == AI_SCHEMA_V2:
        _validate_expected_context(receipt, ai, expected_context)
    elif ai_schema in {AI_SCHEMA_V3, AI_SCHEMA}:
        if expected_context is not None:
            raise ArtifactValidationError(
                "LEGACY_CONTEXT_FORBIDDEN",
                "v3/v4 require an external generation context, not v2 expected lists",
            )
        if (
            generation_context_path is None
            or expected_generation_context_sha256 is None
        ):
            raise ArtifactValidationError(
                "GENERATION_CONTEXT_REQUIRED",
                "v3/v4 validation requires context path and pre-frozen expected sha256",
            )
        if not SHA256_RE.fullmatch(expected_generation_context_sha256):
            raise ArtifactValidationError(
                "GENERATION_CONTEXT_HASH", "expected context sha256 is invalid"
            )
        context_path = generation_context_path.resolve(strict=True)
        try:
            context_path.relative_to(root)
        except ValueError:
            pass
        else:
            raise ArtifactValidationError(
                "GENERATION_CONTEXT_NOT_EXTERNAL",
                "generation context must be outside the artifact output root",
            )
        actual_context_hash = _sha256(context_path)
        if actual_context_hash != expected_generation_context_sha256:
            raise ArtifactValidationError(
                "GENERATION_CONTEXT_HASH_MISMATCH",
                "generation context differs from the pre-generation hash",
            )
        binding = receipt["generation_context"]
        if binding["sha256"] != actual_context_hash:
            raise ArtifactValidationError(
                "GENERATION_CONTEXT_BINDING",
                "receipt generation-context hash differs from actual bytes",
            )
        generation_context = _load_json(context_path)
        generation_context_schema = _validate_generation_context(generation_context)
        expected_generation_schema = (
            GENERATION_CONTEXT_SCHEMA
            if ai_schema == AI_SCHEMA
            else GENERATION_CONTEXT_SCHEMA_V1
        )
        if generation_context_schema != expected_generation_schema:
            raise ArtifactValidationError(
                "SCHEMA_COMPATIBILITY",
                "AI contract and generation context successor levels differ",
            )
        if generation_context_schema == GENERATION_CONTEXT_SCHEMA:
            if project_root is None:
                raise ArtifactValidationError(
                    "PROJECT_ROOT_REQUIRED",
                    "v4 validation requires the current downstream project root",
                )
            resolved_project_root = project_root.resolve(strict=True)
            for route_read in generation_context["project_route_reads"]:
                route_path = _safe_resolve(
                    resolved_project_root,
                    route_read["ref"],
                    "PROJECT_ROUTE_READ_REF",
                )
                if _sha256(route_path) != route_read["sha256"]:
                    raise ArtifactValidationError(
                        "PROJECT_ROUTE_READ_HASH_MISMATCH",
                        f"current project route bytes differ: {route_read['ref']}",
                    )
            project_route_reads_validated = True
        if binding["context_id"] != generation_context["context_id"]:
            raise ArtifactValidationError(
                "GENERATION_CONTEXT_BINDING",
                "receipt generation-context ID differs from actual context",
            )
        context_owners = {
            "project_intelligence": generation_context["oracle_owner"],
            "plan_tree": generation_context["dependency_owner"],
        }
        for key, owner in context_owners.items():
            receipt_owner = receipt["owner_reads"][key]
            if (
                owner["owner_ref"] != receipt_owner["ref"]
                or owner["owner_sha256"] != receipt_owner["sha256"]
            ):
                raise ArtifactValidationError(
                    "GENERATION_CONTEXT_OWNER_MISMATCH",
                    f"context owner differs from receipt: {key}",
                )
        _validate_context_binding(receipt, ai, generation_context)
        generation_context_validated = True
    human = human_path.read_text(encoding="utf-8")
    labels, _ = _orientation_section(human, receipt["language"])
    subject_label = "主题" if receipt["language"] == "zh-CN" else "Subject"
    human_subject = _nfc(" ".join(labels[subject_label].split()))
    ai_subject = _nfc(" ".join(ai["subject"].split()))
    if human_subject != ai_subject:
        raise ArtifactValidationError(
            "HUMAN_SUBJECT_MISMATCH", "human subject differs from AI subject"
        )
    if ai_schema == AI_SCHEMA:
        assert generation_context is not None
        _validate_human_project_position(
            labels,
            receipt["language"],
            generation_context["navigation_context"],
        )
    paths_and_hashes = [
        (
            receipt["projection_refs"]["human_brief_ref"],
            human_path,
            receipt["projection_sha256"]["human_brief_ref"],
        ),
        (
            receipt["projection_refs"]["ai_working_contract_ref"],
            ai_path,
            receipt["projection_sha256"]["ai_working_contract_ref"],
        ),
    ]
    paths_and_hashes.extend(
        (ref, path, receipt["projection_sha256"]["evidence_appendix_refs"][ref])
        for ref, path in zip(
            receipt["projection_refs"]["evidence_appendix_refs"], evidence_paths
        )
    )
    for ref, path, expected in paths_and_hashes:
        actual = _sha256(path)
        if actual != expected:
            raise ArtifactValidationError(
                "BINDING_HASH_MISMATCH", f"hash mismatch: {ref}"
            )
    owners = receipt["owner_reads"]
    for key, filename in (
        ("project_intelligence", "project-intelligence.md"),
        ("plan_tree", "plan-tree.md"),
    ):
        owner_path = _safe_resolve(owner_root, owners[key]["ref"], "REF_UNSAFE")
        if not owner_path.name.lower() == filename:
            raise ArtifactValidationError(
                "OWNER_READ_MISSING", f"wrong owner file: {key}"
            )
        if _sha256(owner_path) != owners[key]["sha256"]:
            raise ArtifactValidationError(
                "OWNER_READ_HASH_MISMATCH", f"owner hash mismatch: {key}"
            )
    return {
        "contract": CONTRACT,
        "status": "pass",
        "projection_binding_validated": True,
        "receipt_schema": receipt_schema,
        "ai_schema": ai_schema,
        "runtime_profile": receipt.get("runtime_profile", receipt.get("profile")),
        "runtime_profile_source": receipt.get("runtime_profile_source"),
        "expected_context_validated": ai_schema == AI_SCHEMA_V2,
        "generation_context_validated": generation_context_validated,
        "project_route_reads_validated": project_route_reads_validated,
        "repair_attempts": receipt["repair_attempts"],
        "checks": {
            "human_orientation": "pass",
            "ai_contract": "pass",
            "projection_binding": "pass",
            "owner_reads": "pass",
            "actual_hashes": "pass",
            "scope_isolation": (
                "pass"
                if ai_schema in {AI_SCHEMA_V2, AI_SCHEMA_V3, AI_SCHEMA}
                else "legacy_read_only"
            ),
            "operation_policy": "pass"
            if ai_schema in {AI_SCHEMA_V3, AI_SCHEMA}
            else "legacy_read_only",
            "impact_isolation": "pass"
            if ai_schema in {AI_SCHEMA_V3, AI_SCHEMA}
            else "legacy_read_only",
            "route_permission": "pass"
            if ai_schema in {AI_SCHEMA_V3, AI_SCHEMA}
            else "legacy_read_only",
            "unknown_integrity": "pass"
            if ai_schema in {AI_SCHEMA_V3, AI_SCHEMA}
            else "legacy_read_only",
            "navigation_context": "pass"
            if ai_schema == AI_SCHEMA
            else "legacy_read_only",
            "required_authority_findings": "pass"
            if ai_schema == AI_SCHEMA
            else "legacy_read_only",
            "human_project_position": "pass"
            if ai_schema == AI_SCHEMA
            else "legacy_read_only",
            "project_route_reads": "pass"
            if ai_schema == AI_SCHEMA
            else "legacy_read_only",
            "schema_lifecycle": (
                "current" if ai_schema == AI_SCHEMA else "legacy_read_only"
            ),
        },
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifact-root", type=Path, required=True)
    parser.add_argument("--owner-root", type=Path, required=True)
    parser.add_argument("--receipt-ref", default="CANARY-FINAL-RECEIPT.json")
    parser.add_argument("--expected-runtime-profile", choices=sorted(RUNTIME_PROFILES))
    parser.add_argument(
        "--expected-runtime-profile-source",
        choices=sorted(RUNTIME_PROFILE_SOURCES),
    )
    parser.add_argument("--expected-affected-node-ref", action="append")
    parser.add_argument("--expected-blocked-scope-ref", action="append")
    parser.add_argument("--expected-unaffected-scope-ref", action="append")
    parser.add_argument(
        "--expected-scope-isolation-status", choices=("proven", "unknown")
    )
    parser.add_argument("--generation-context", type=Path)
    parser.add_argument("--expected-generation-context-sha256")
    parser.add_argument("--project-root", type=Path)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    context_values = (
        args.expected_runtime_profile,
        args.expected_runtime_profile_source,
        args.expected_affected_node_ref,
        args.expected_blocked_scope_ref,
        args.expected_unaffected_scope_ref,
        args.expected_scope_isolation_status,
    )
    expected_context = None
    if any(value is not None for value in context_values):
        expected_context = {
            "runtime_profile": args.expected_runtime_profile,
            "runtime_profile_source": args.expected_runtime_profile_source,
            "affected_node_refs": args.expected_affected_node_ref or [],
            "blocked_scope": args.expected_blocked_scope_ref or [],
            "unaffected_scope": args.expected_unaffected_scope_ref or [],
            "scope_isolation_status": args.expected_scope_isolation_status,
        }
    try:
        report = validate_artifacts(
            args.artifact_root,
            args.owner_root,
            args.receipt_ref,
            project_root=args.project_root,
            expected_context=expected_context,
            generation_context_path=args.generation_context,
            expected_generation_context_sha256=(
                args.expected_generation_context_sha256
            ),
        )
    except (ArtifactValidationError, OSError, KeyError, TypeError, ValueError) as exc:
        if isinstance(exc, ArtifactValidationError):
            report = {
                "contract": CONTRACT,
                "status": "fail",
                "projection_binding_validated": False,
                "errors": [{"code": exc.code, "detail": exc.detail}],
            }
        else:
            report = {
                "contract": CONTRACT,
                "status": "fail",
                "projection_binding_validated": False,
                "errors": [{"code": "IO_ERROR", "detail": str(exc)}],
            }
        print(json.dumps(report, ensure_ascii=False, sort_keys=True))
        return 1
    print(json.dumps(report, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
