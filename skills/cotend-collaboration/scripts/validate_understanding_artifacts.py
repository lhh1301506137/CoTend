class ArtifactValidationError(ValueError):
    """A stable, user-actionable validation error."""

    def __init__(self, code: str, detail: str):
        super().__init__(detail)
        self.code = code
        self.detail = detail


def _nfc(value: str) -> str:
    return unicodedata.normalize("NFC", value)


def _duplicate_safe_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for raw_key, value in pairs:
        key = _nfc(raw_key)
        if key in result:
            raise ArtifactValidationError("JSON_DUPLICATE_KEY", f"duplicate key: {key}")
        result[key] = value
    return result


def _load_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(
            path.read_text(encoding="utf-8"), object_pairs_hook=_duplicate_safe_pairs
        )
    except ArtifactValidationError:
        raise
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise ArtifactValidationError("JSON_INVALID", f"{path.name}: {exc}") from exc
    if not isinstance(value, dict):
        raise ArtifactValidationError(
            "JSON_ROOT", f"{path.name} must contain an object"
        )
    return value


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _nonempty(value: Any, code: str, field: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ArtifactValidationError(code, f"{field} must be a non-empty string")
    return value.strip()


def _string_list(
    value: Any, code: str, field: str, *, allow_empty: bool = True
) -> list[str]:
    if not isinstance(value, list) or (not allow_empty and not value):
        raise ArtifactValidationError(code, f"{field} must be a list")
    result: list[str] = []
    for item in value:
        result.append(_nonempty(item, code, field))
    return result


def _unique_string_list(
    value: Any, code: str, field: str, *, allow_empty: bool = True
) -> list[str]:
    result = _string_list(value, code, field, allow_empty=allow_empty)
    if len(result) != len(set(result)):
        raise ArtifactValidationError(code, f"{field} contains duplicate refs")
    return result


def _nullable_anchored_ref(value: Any, code: str, field: str) -> str | None:
    if value is None:
        return None
    ref = _nonempty(value, code, field)
    path, marker, anchor = ref.partition("#")
    if not marker or not path.strip() or not anchor.strip() or "#" in anchor:
        raise ArtifactValidationError(code, f"{field} must be an anchored ref")
    normalized_path = path.replace("\\", "/")
    parts = Path(normalized_path).parts
    if (
        not SAFE_REF_RE.fullmatch(path)
        or Path(path).is_absolute()
        or any(part in {"", ".", ".."} for part in parts)
    ):
        raise ArtifactValidationError(code, f"{field} has an unsafe ref path")
    return ref


def _safe_relative_file_ref(value: Any, code: str, field: str) -> str:
    ref = _nonempty(value, code, field)
    if "#" in ref or not SAFE_REF_RE.fullmatch(ref) or Path(ref).is_absolute():
        raise ArtifactValidationError(code, f"{field} must be a safe relative file ref")
    normalized = ref.replace("\\", "/")
    if any(part in {"", ".", ".."} for part in Path(normalized).parts):
        raise ArtifactValidationError(code, f"{field} has an unsafe ref path")
    return normalized


def _anchored_ref_path(value: Any, code: str, field: str) -> str:
    ref = _nullable_anchored_ref(value, code, field)
    assert ref is not None
    return ref.split("#", 1)[0].replace("\\", "/")


def _stable_identity(value: Any, code: str, field: str, prefix: str) -> str:
    identity = _nonempty(value, code, field)
    if not identity.startswith(prefix):
        raise ArtifactValidationError(code, f"{field} must start with {prefix}")
    if (
        DATE_TOKEN_RE.search(identity)
        or VERSION_TOKEN_RE.search(identity)
        or REVISION_TOKEN_RE.search(identity)
    ):
        raise ArtifactValidationError(
            code, f"{field} contains a date, version, or revision token"
        )
    return identity


def _validate_entity(value: Any, *, code: str = "ENTITY_IDENTITY") -> dict[str, Any]:
    fields = {"entity_id", "semantic_key", "identity_status", "owner_ref"}
    if not isinstance(value, dict) or set(value) != fields:
        raise ArtifactValidationError(code, "understanding_entity has wrong fields")
    _stable_identity(value["entity_id"], code, "entity_id", "UE-")
    semantic_key = _nonempty(value["semantic_key"], code, "semantic_key")
    if (
        DATE_TOKEN_RE.search(semantic_key)
        or VERSION_TOKEN_RE.search(semantic_key)
        or REVISION_TOKEN_RE.search(semantic_key)
    ):
        raise ArtifactValidationError(code, "semantic_key is revision-specific")
    if value["identity_status"] not in {"owner_anchored", "provisional"}:
        raise ArtifactValidationError(code, "identity_status is unsupported")
    owner_ref = _nullable_anchored_ref(value["owner_ref"], code, "owner_ref")
    if value["identity_status"] == "owner_anchored" and owner_ref is None:
        raise ArtifactValidationError(code, "owner_anchored entity requires owner_ref")
    if value["identity_status"] == "provisional" and owner_ref is not None:
        raise ArtifactValidationError(code, "provisional entity cannot claim owner_ref")
    return value


def _validate_working_refs(value: Any, projection_refs: dict[str, Any]) -> None:
    if not isinstance(value, dict) or set(value) != set(WORK_REF_OWNERS):
        raise ArtifactValidationError("WORKING_REF", "working_refs have wrong fields")
    projection_names = {
        ref.replace("\\", "/").casefold()
        for ref in (
            projection_refs["human_brief_ref"],
            projection_refs["ai_working_contract_ref"],
            *projection_refs["evidence_appendix_refs"],
        )
    }
    for field, allowed_owners in WORK_REF_OWNERS.items():
        item = value[field]
        if item is None:
            continue
        if not isinstance(item, dict) or set(item) != {"owner", "ref"}:
            raise ArtifactValidationError("WORKING_REF", f"{field} has wrong fields")
        if item["owner"] not in allowed_owners:
            raise ArtifactValidationError(
                "WORKING_REF_OWNER", f"{field} has the wrong owner"
            )
        ref = _nullable_anchored_ref(item["ref"], "WORKING_REF", field)
        assert ref is not None
        if ref.split("#", 1)[0].replace("\\", "/").casefold() in projection_names:
            raise ArtifactValidationError(
                "WORKING_REF_SELF_REFERENCE",
                f"{field} cannot use a generated projection as truth",
            )


def _validate_operation_context(value: Any) -> None:
    fields = {
        "mode",
        "project_write_policy",
        "artifact_output_policy",
        "product_work_requested",
        "authorized_scope_refs",
        "authorization_ref",
    }
    if not isinstance(value, dict) or set(value) != fields:
        raise ArtifactValidationError(
            "OPERATION_CONTEXT", "operation_context has wrong fields"
        )
    if value["mode"] not in {"read_only_project", "bounded_project_write"}:
        raise ArtifactValidationError("OPERATION_CONTEXT", "operation mode is invalid")
    if value["project_write_policy"] not in {"none", "bounded"}:
        raise ArtifactValidationError(
            "OPERATION_CONTEXT", "project_write_policy is invalid"
        )
    if value["artifact_output_policy"] not in {
        "none",
        "create_only",
        "bounded_update",
    }:
        raise ArtifactValidationError(
            "OPERATION_CONTEXT", "artifact_output_policy is invalid"
        )
    if value["product_work_requested"] not in {"yes", "no"}:
        raise ArtifactValidationError(
            "OPERATION_CONTEXT", "product_work_requested must be yes/no"
        )
    _unique_string_list(
        value["authorized_scope_refs"], "OPERATION_CONTEXT", "authorized_scope_refs"
    )
    _nonempty(value["authorization_ref"], "OPERATION_CONTEXT", "authorization_ref")
    if value["mode"] == "read_only_project" and value["project_write_policy"] != "none":
        raise ArtifactValidationError(
            "OPERATION_CONTEXT", "read_only_project requires project write policy none"
        )
    if (
        value["mode"] == "bounded_project_write"
        and value["project_write_policy"] != "bounded"
    ):
        raise ArtifactValidationError(
            "OPERATION_CONTEXT", "bounded_project_write requires bounded write policy"
        )


def _validate_impact_scope(value: Any) -> None:
    fields = {
        "affected_node_refs",
        "blocked_scope",
        "unaffected_scope",
        "scope_isolation",
    }
    if not isinstance(value, dict) or set(value) != fields:
        raise ArtifactValidationError("IMPACT_SCOPE", "impact_scope has wrong fields")
    affected = _unique_string_list(
        value["affected_node_refs"], "IMPACT_SCOPE", "affected_node_refs"
    )
    blocked = _unique_string_list(
        value["blocked_scope"], "IMPACT_SCOPE", "blocked_scope"
    )
    unaffected = _unique_string_list(
        value["unaffected_scope"], "IMPACT_SCOPE", "unaffected_scope"
    )
    for ref in affected + blocked + unaffected:
        if ref.startswith(("operation:", "read:", "evidence:")):
            raise ArtifactValidationError(
                "IMPACT_LAYER_MIXED", f"non-product ref entered impact scope: {ref}"
            )
    affected_set = set(affected)
    blocked_set = set(blocked)
    unaffected_set = set(unaffected)
    if blocked_set & unaffected_set or affected_set & unaffected_set:
        raise ArtifactValidationError("IMPACT_SCOPE", "impact scopes overlap")
    if not blocked_set <= affected_set:
        raise ArtifactValidationError(
            "IMPACT_SCOPE", "blocked_scope must be inside affected_node_refs"
        )
    proof = value["scope_isolation"]
    if not isinstance(proof, dict) or set(proof) != {
        "status",
        "minimum_dependency_closure",
        "basis_refs",
    }:
        raise ArtifactValidationError(
            "IMPACT_SCOPE", "scope isolation has wrong fields"
        )
    if proof["status"] not in {"proven", "unknown"}:
        raise ArtifactValidationError(
            "IMPACT_SCOPE", "scope isolation status is invalid"
        )
    closure = _unique_string_list(
        proof["minimum_dependency_closure"],
        "IMPACT_SCOPE",
        "minimum_dependency_closure",
    )
    _unique_string_list(
        proof["basis_refs"], "IMPACT_SCOPE", "basis_refs", allow_empty=False
    )
    if set(closure) != affected_set:
        raise ArtifactValidationError(
            "IMPACT_CLOSURE_MISMATCH",
            "affected_node_refs must equal the minimum dependency closure",
        )
    if unaffected and proof["status"] != "proven":
        raise ArtifactValidationError(
            "IMPACT_SCOPE", "unaffected scope requires proven isolation"
        )


def _validate_route_permission(
    value: Any, operation_context: dict[str, Any], impact_scope: dict[str, Any]
) -> None:
    if not isinstance(value, dict) or set(value) != {
        "requested_route_ref",
        "decision",
        "basis_refs",
    }:
        raise ArtifactValidationError(
            "ROUTE_PERMISSION", "route_permission has wrong fields"
        )
    requested = value["requested_route_ref"]
    if requested is not None:
        requested = _nonempty(requested, "ROUTE_PERMISSION", "requested_route_ref")
    if value["decision"] not in {"not_requested", "allowed", "held", "unknown"}:
        raise ArtifactValidationError("ROUTE_PERMISSION", "route decision is invalid")
    _unique_string_list(
        value["basis_refs"], "ROUTE_PERMISSION", "basis_refs", allow_empty=False
    )
    product_requested = operation_context["product_work_requested"]
    if value["decision"] == "not_requested":
        if product_requested != "no" or requested is not None:
            raise ArtifactValidationError(
                "ROUTE_PERMISSION", "not_requested requires no product route request"
            )
        return
    if product_requested != "yes" or requested is None:
        raise ArtifactValidationError(
            "ROUTE_PERMISSION", "a route decision requires an explicit product request"
        )
    blocked = set(impact_scope["blocked_scope"])
    isolation = impact_scope["scope_isolation"]["status"]
    if value["decision"] == "allowed" and (
        requested in blocked or isolation != "proven"
    ):
        raise ArtifactValidationError(
            "ROUTE_PERMISSION", "allowed route is blocked or isolation is unknown"
        )
    evaluated = set(impact_scope["affected_node_refs"]) | set(
        impact_scope["unaffected_scope"]
    )
    if value["decision"] == "allowed" and requested not in evaluated:
        raise ArtifactValidationError(
            "ROUTE_PERMISSION",
            "allowed route is absent from the evaluated impact/isolation scope",
        )
    if value["decision"] == "held" and requested not in blocked:
        raise ArtifactValidationError(
            "ROUTE_PERMISSION", "held route must be named in blocked_scope"
        )
    if value["decision"] == "unknown" and isolation != "unknown":
        raise ArtifactValidationError(
            "ROUTE_PERMISSION", "unknown route requires unknown isolation"
        )


def _validate_unknowns(
    value: Any, entity_id: str, impact_scope: dict[str, Any]
) -> list[dict[str, Any]]:
    fields = {
        "unknown_id",
        "entity_id",
        "owner",
        "status",
        "impact_scope_refs",
        "blocking_boundary",
        "blocked_scope_refs",
        "evidence_status",
        "user_consequence_ref",
        "recommendation_ref",
        "resolution_ref",
    }
    if not isinstance(value, list):
        raise ArtifactValidationError("UNKNOWN_SCHEMA", "unknowns must be a list")
    result: list[dict[str, Any]] = []
    ids: set[str] = set()
    affected = set(impact_scope["affected_node_refs"])
    for unknown in value:
        if not isinstance(unknown, dict) or set(unknown) != fields:
            raise ArtifactValidationError("UNKNOWN_SCHEMA", "unknown has wrong fields")
        unknown_id = _stable_identity(
            unknown["unknown_id"], "UNKNOWN_SCHEMA", "unknown_id", "U-"
        )
        if unknown_id in ids:
            raise ArtifactValidationError("UNKNOWN_SCHEMA", "duplicate unknown_id")
        ids.add(unknown_id)
        if unknown["entity_id"] != entity_id:
            raise ArtifactValidationError("UNKNOWN_SCHEMA", "unknown entity_id differs")
        if unknown["owner"] not in UNKNOWN_OWNERS:
            raise ArtifactValidationError("UNKNOWN_OWNER", str(unknown["owner"]))
        if unknown["status"] not in {"open", "resolved", "superseded"}:
            raise ArtifactValidationError("UNKNOWN_SCHEMA", "unknown status is invalid")
        impact_refs = _unique_string_list(
            unknown["impact_scope_refs"], "UNKNOWN_SCHEMA", "impact_scope_refs"
        )
        blocked_refs = _unique_string_list(
            unknown["blocked_scope_refs"], "UNKNOWN_SCHEMA", "blocked_scope_refs"
        )
        if not set(impact_refs) <= affected:
            raise ArtifactValidationError(
                "UNKNOWN_SCOPE", "unknown impact scope exceeds affected scope"
            )
        if not set(blocked_refs) <= set(impact_refs):
            raise ArtifactValidationError(
                "UNKNOWN_SCOPE",
                "unknown blocked scope exceeds its impact scope",
            )
        if unknown["blocking_boundary"] not in {
            "none",
            "protected_meaning",
            "route_implementation",
            "destructive_action",
            "release",
            "evidence_claim",
        }:
            raise ArtifactValidationError(
                "UNKNOWN_SCHEMA", "unknown blocking boundary is invalid"
            )
        if unknown["evidence_status"] not in {
            "unexamined",
            "missing",
            "partial",
            "sufficient",
            "not_applicable",
        }:
            raise ArtifactValidationError(
                "UNKNOWN_SCHEMA", "unknown evidence status is invalid"
            )
        consequence = _nullable_anchored_ref(
            unknown["user_consequence_ref"], "UNKNOWN_SCHEMA", "user_consequence_ref"
        )
        recommendation = _nullable_anchored_ref(
            unknown["recommendation_ref"], "UNKNOWN_SCHEMA", "recommendation_ref"
        )
        resolution = _nullable_anchored_ref(
            unknown["resolution_ref"], "UNKNOWN_SCHEMA", "resolution_ref"
        )
        if unknown["status"] == "open" and resolution is not None:
            raise ArtifactValidationError(
                "UNKNOWN_STATE", "open unknown has resolution"
            )
        if unknown["status"] != "open":
            if resolution is None or blocked_refs:
                raise ArtifactValidationError(
                    "UNKNOWN_STATE",
                    "closed unknown requires resolution and no blocked scope",
                )
        if unknown["blocking_boundary"] == "none" and blocked_refs:
            raise ArtifactValidationError(
                "UNKNOWN_STATE", "non-blocking unknown has blocked scope"
            )
        if unknown["owner"] == "user_value_unknown" and unknown["status"] == "open":
            if consequence is None or recommendation is None:
                raise ArtifactValidationError(
                    "UNKNOWN_USER_GATE",
                    "open user-value unknown requires consequence and recommendation refs",
                )
        result.append(unknown)
    return result


def _walk_names(value: Any) -> Iterable[str]:
    if isinstance(value, dict):
        for key, child in value.items():
            yield key
            yield from _walk_names(child)
    elif isinstance(value, list):
        for child in value:
            yield from _walk_names(child)


def _safe_resolve(root: Path, ref: str, code: str) -> Path:
    _nonempty(ref, code, "ref")
    if not SAFE_REF_RE.fullmatch(ref) or Path(ref).is_absolute():
        raise ArtifactValidationError(code, f"unsafe relative ref: {ref}")
    parts = Path(ref.replace("\\", "/")).parts
    if any(part in {"", ".", ".."} for part in parts):
        raise ArtifactValidationError(code, f"unsafe relative ref: {ref}")
    base = root.resolve(strict=True)
    cursor = base
    for part in parts:
        case_matches = [
            entry.name
            for entry in cursor.iterdir()
            if entry.name.casefold() == part.casefold()
        ]
        if len(case_matches) != 1 or case_matches[0] != part:
            raise ArtifactValidationError(code, f"ref case is not exact: {ref}")
        cursor = (cursor / case_matches[0]).resolve(strict=True)
        try:
            cursor.relative_to(base)
        except ValueError as exc:
            raise ArtifactValidationError(code, f"ref escapes root: {ref}") from exc
    target = cursor
    try:
        target.relative_to(base)
    except ValueError as exc:
        raise ArtifactValidationError(code, f"ref escapes root: {ref}") from exc
    if not target.is_file():
        raise ArtifactValidationError("FILE_MISSING", f"ref is not a file: {ref}")
    return target


def _assert_projection_refs(refs: Any, code: str) -> dict[str, Any]:
    if not isinstance(refs, dict) or set(refs) != AI_PROJECTION_FIELDS:
        raise ArtifactValidationError(code, "projection_refs have the wrong fields")
    _nonempty(refs["human_brief_ref"], code, "human_brief_ref")
    _nonempty(refs["ai_working_contract_ref"], code, "ai_working_contract_ref")
    _string_list(
        refs["evidence_appendix_refs"],
        code,
        "evidence_appendix_refs",
        allow_empty=False,
    )
    return refs


def _validate_ai_common(
    contract: dict[str, Any], fields: set[str], schema: str
) -> None:
    if set(contract) != fields:
        missing = sorted(fields - set(contract))
        extra = sorted(set(contract) - fields)
        raise ArtifactValidationError("AI_SCHEMA", f"missing={missing}, extra={extra}")
    _nonempty(contract["contract_schema"], "AI_SCHEMA", "contract_schema")
    if contract["contract_schema"] != schema:
        raise ArtifactValidationError("AI_SCHEMA", "unsupported contract_schema")
    for field in (
        "contract_id",
        "understanding_entity_id",
        "revision_id",
        "subject",
        "provenance",
        "authority",
        "freshness",
        "time_range",
        "current_ref",
        "readiness",
    ):
        _nonempty(contract[field], "AI_FIELD", field)
    _assert_projection_refs(contract["projection_refs"], "AI_PROJECTION_REFS")
    for field in (
        "affected_node_refs",
        "dependency_refs",
        "evidence_refs",
        "invalidation_conditions",
    ):
        _string_list(contract[field], "AI_FIELD", field)
    for field in ("candidate_ref", "plan_ref", "result_ref", "gap_ref"):
        _nonempty(contract[field], "AI_FIELD", field)
    if contract["implementation_permission"] not in {"yes", "no"}:
        raise ArtifactValidationError(
            "AI_FIELD", "implementation_permission must be yes/no"
        )
    unknowns = contract["unknowns"]
    if not isinstance(unknowns, list):
        raise ArtifactValidationError("UNKNOWN_SCHEMA", "unknowns must be a list")
    for unknown in unknowns:
        if not isinstance(unknown, dict) or set(unknown) != {
            "unknown_ref",
            "owner",
            "blocking_before",
        }:
            raise ArtifactValidationError("UNKNOWN_SCHEMA", "unknown has wrong fields")
        _nonempty(unknown["unknown_ref"], "UNKNOWN_SCHEMA", "unknown_ref")
        if unknown["owner"] not in UNKNOWN_OWNERS:
            raise ArtifactValidationError("UNKNOWN_OWNER", str(unknown["owner"]))
        _nonempty(unknown["blocking_before"], "UNKNOWN_SCHEMA", "blocking_before")
    for name in _walk_names(contract):
        if name in FORBIDDEN_NAMES:
            raise ArtifactValidationError(
                "AI_FORBIDDEN_BODY", f"forbidden field: {name}"
            )
    encoded = json.dumps(
        contract, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    if len(encoded) > MAX_AI_BYTES:
        raise ArtifactValidationError(
            "AI_TOO_LARGE", f"normalized contract is {len(encoded)} bytes"
        )
    serialized = json.dumps(contract, ensure_ascii=False)
    if any(label in serialized for label in FORBIDDEN_LABELS):
        raise ArtifactValidationError(
            "PROJECTION_CANONICAL_LABEL_FORBIDDEN", "canonical projection label"
        )


def _validate_scope_isolation(contract: dict[str, Any]) -> None:
    """Require an explicit, minimum dependency closure for successor contracts."""
    for field in ("blocked_scope", "unaffected_scope"):
        _string_list(contract[field], "SCOPE_ISOLATION", field)
        values = contract[field]
        if len(values) != len(set(values)):
            raise ArtifactValidationError(
                "SCOPE_ISOLATION", f"{field} contains duplicate refs"
            )
    affected = contract["affected_node_refs"]
    if len(affected) != len(set(affected)):
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "affected_node_refs contains duplicate refs"
        )
    blocked = set(contract["blocked_scope"])
    unaffected = set(contract["unaffected_scope"])
    affected_set = set(affected)
    if blocked & unaffected:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "blocked_scope and unaffected_scope overlap"
        )
    if affected_set & unaffected:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "unaffected_scope intersects affected_node_refs"
        )
    if not blocked <= affected_set:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "blocked_scope must be inside affected_node_refs"
        )
    proof = contract["scope_isolation"]
    if not isinstance(proof, dict) or set(proof) != {
        "status",
        "minimum_dependency_closure",
        "basis_refs",
    }:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "scope_isolation proof has the wrong fields"
        )
    if proof["status"] not in {"proven", "unknown"}:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "scope isolation status must be proven or unknown"
        )
    closure = _string_list(
        proof["minimum_dependency_closure"],
        "SCOPE_ISOLATION",
        "minimum_dependency_closure",
        allow_empty=False,
    )
    _string_list(
        proof["basis_refs"], "SCOPE_ISOLATION", "basis_refs", allow_empty=False
    )
    if len(closure) != len(set(closure)):
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "minimum_dependency_closure contains duplicates"
        )
    if set(closure) != affected_set:
        raise ArtifactValidationError(
            "SCOPE_CLOSURE_MISMATCH",
            "affected_node_refs must equal the declared minimum dependency closure",
        )
    if unaffected and proof["status"] != "proven":
        raise ArtifactValidationError(
            "SCOPE_ISOLATION",
            "unaffected continuation requires positively proven isolation",
        )
    if proof["status"] == "unknown" and contract["implementation_permission"] == "yes":
        raise ArtifactValidationError(
            "SCOPE_ISOLATION",
            "unknown isolation cannot grant implementation permission",
        )
    if contract["implementation_permission"] == "no" and not blocked:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION", "implementation_permission=no requires blocked_scope"
        )
    if contract["implementation_permission"] == "yes" and blocked:
        raise ArtifactValidationError(
            "SCOPE_ISOLATION",
            "implementation_permission=yes requires an empty blocked_scope",
        )


def _validate_authority_findings(
    findings: Any,
    *,
    authority: str | None = None,
    required_route_findings: bool = False,
) -> list[dict[str, Any]]:
    if not isinstance(findings, list):
        raise ArtifactValidationError(
            "AUTHORITY_FINDING", "authority_findings must be a list"
        )
    kinds: set[str] = set()
    identities: set[tuple[str, str, str, str]] = set()
    refs: set[str] = set()
    result: list[dict[str, Any]] = []
    for finding in findings:
        if not isinstance(finding, dict) or set(finding) != {
            "kind",
            "ref",
            "owner",
            "disposition",
        }:
            raise ArtifactValidationError(
                "AUTHORITY_FINDING", "authority finding has the wrong fields"
            )
        if finding["kind"] not in {"stale_mirror", "authority_conflict"}:
            raise ArtifactValidationError(
                "AUTHORITY_FINDING", "unsupported authority finding kind"
            )
        if finding["owner"] not in {
            "plan_tree",
            "project_intelligence",
            "semantic_alignment",
        }:
            raise ArtifactValidationError(
                "AUTHORITY_FINDING", "authority finding owner is not canonical"
            )
        expected_disposition = (
            "governance_maintenance"
            if finding["kind"] == "stale_mirror"
            else "stop_affected_route"
        )
        if finding["disposition"] != expected_disposition:
            raise ArtifactValidationError(
                "AUTHORITY_FINDING", "authority finding disposition is inconsistent"
            )
        ref = _nonempty(finding["ref"], "AUTHORITY_FINDING", "ref")
        if required_route_findings and finding["kind"] == "stale_mirror":
            if finding["owner"] != "plan_tree":
                raise ArtifactValidationError(
                    "STALE_MIRROR_MISCLASSIFIED",
                    "a required route mirror must defer to Plan Tree",
                )
        if (
            required_route_findings
            and finding["kind"] == "authority_conflict"
            and finding["owner"] == "plan_tree"
        ):
            raise ArtifactValidationError(
                "STALE_MIRROR_MISCLASSIFIED",
                "a route-bearing non-owner mirror cannot become a Plan Tree authority conflict",
            )
        identity = (
            finding["kind"],
            ref,
            finding["owner"],
            finding["disposition"],
        )
        if identity in identities or ref in refs:
            raise ArtifactValidationError(
                "AUTHORITY_FINDING", "authority findings contain duplicate refs"
            )
        identities.add(identity)
        refs.add(ref)
        kinds.add(finding["kind"])
        result.append(finding)
    if authority is not None:
        if (
            "stale_mirror" in kinds
            and "authority_conflict" not in kinds
            and authority == "conflict"
        ):
            raise ArtifactValidationError(
                "STALE_MIRROR_AUTHORITY_CONFLICT",
                "a stale non-owner mirror cannot become authority conflict",
            )
        if authority == "conflict" and "authority_conflict" not in kinds:
            raise ArtifactValidationError(
                "AUTHORITY_FINDING",
                "authority=conflict requires a same-level authority_conflict finding",
            )
        if "authority_conflict" in kinds and authority != "conflict":
            raise ArtifactValidationError(
                "AUTHORITY_FINDING",
                "an authority_conflict finding requires authority=conflict",
            )
    return result


def _validate_owner_precedence(contract: dict[str, Any]) -> None:
    precedence = contract["owner_precedence"]
    if not isinstance(precedence, dict) or set(precedence) != {
        "navigation",
        "understanding",
        "semantic_confirmation",
    }:
        raise ArtifactValidationError(
            "OWNER_PRECEDENCE", "owner_precedence has the wrong fields"
        )
    expected = {
        "navigation": "plan_tree",
        "understanding": "project_intelligence",
        "semantic_confirmation": "semantic_alignment",
    }
    if precedence != expected:
        raise ArtifactValidationError(
            "OWNER_PRECEDENCE", "owner precedence does not name canonical owners"
        )
    _validate_authority_findings(
        contract["authority_findings"], authority=contract["authority"]
    )


def _validate_navigation_context(value: Any) -> dict[str, Any]:
    fields = {
        "plan_tree_status",
        "active_path",
        "active_node_ref",
        "current_next_leaf_ref",
        "reliable_boundary",
        "subject_route_relations",
        "basis_refs",
    }
    if not isinstance(value, dict) or set(value) != fields:
        raise ArtifactValidationError(
            "NAVIGATION_CONTEXT", "navigation_context has wrong fields"
        )
    if value["plan_tree_status"] not in PLAN_TREE_STATUSES:
        raise ArtifactValidationError(
            "NAVIGATION_CONTEXT", "plan_tree_status is invalid"
        )
    active_path = _unique_string_list(
        value["active_path"], "NAVIGATION_CONTEXT", "active_path"
    )
    active_node = value["active_node_ref"]
    if active_node is not None:
        active_node = _nonempty(
            active_node, "NAVIGATION_CONTEXT", "active_node_ref"
        )
    if active_path:
        if active_node != active_path[-1]:
            raise ArtifactValidationError(
                "NAVIGATION_PATH_MISMATCH",
                "active_node_ref must equal the last active_path item",
            )
    elif active_node is not None or value["plan_tree_status"] != "unknown":
        raise ArtifactValidationError(
            "NAVIGATION_PATH_MISMATCH",
            "an empty active_path is valid only for an explicitly unknown route",
        )
    next_leaf = value["current_next_leaf_ref"]
    if next_leaf is not None:
        _nonempty(next_leaf, "NAVIGATION_CONTEXT", "current_next_leaf_ref")

    boundary = value["reliable_boundary"]
    boundary_fields = {
        "earliest_trustworthy_ref",
        "first_invalid_or_unverified_ref",
        "first_invalid_or_unverified_state",
    }
    if not isinstance(boundary, dict) or set(boundary) != boundary_fields:
        raise ArtifactValidationError(
            "RELIABLE_BOUNDARY", "reliable_boundary has wrong fields"
        )
    boundary_values = [boundary[field] for field in boundary_fields]
    if all(item is None for item in boundary_values):
        pass
    elif any(item is None for item in boundary_values):
        raise ArtifactValidationError(
            "RELIABLE_BOUNDARY_MISMATCH",
            "reliable boundary refs and state must be jointly known or null",
        )
    else:
        _nonempty(
            boundary["earliest_trustworthy_ref"],
            "RELIABLE_BOUNDARY",
            "earliest_trustworthy_ref",
        )
        _nonempty(
            boundary["first_invalid_or_unverified_ref"],
            "RELIABLE_BOUNDARY",
            "first_invalid_or_unverified_ref",
        )
        if boundary["first_invalid_or_unverified_state"] not in (
            INVALID_OR_UNVERIFIED_STATES
        ):
            raise ArtifactValidationError(
                "RELIABLE_BOUNDARY", "first invalid/unverified state is invalid"
            )

    relations = value["subject_route_relations"]
    if not isinstance(relations, list) or not relations:
        raise ArtifactValidationError(
            "SUBJECT_ROUTE_RELATION",
            "subject_route_relations must contain the material subject",
        )
    subjects: set[str] = set()
    for relation in relations:
        if not isinstance(relation, dict) or set(relation) != {
            "subject_ref",
            "relation",
            "basis_refs",
        }:
            raise ArtifactValidationError(
                "SUBJECT_ROUTE_RELATION", "subject route relation has wrong fields"
            )
        subject_ref = _nonempty(
            relation["subject_ref"], "SUBJECT_ROUTE_RELATION", "subject_ref"
        )
        if subject_ref in subjects:
            raise ArtifactValidationError(
                "SUBJECT_ROUTE_RELATION", "duplicate subject route relation"
            )
        subjects.add(subject_ref)
        relation_kind = relation["relation"]
        if relation_kind not in SUBJECT_ROUTE_RELATIONS:
            raise ArtifactValidationError(
                "SUBJECT_ROUTE_RELATION", "unsupported subject route relation"
            )
        _unique_string_list(
            relation["basis_refs"],
            "SUBJECT_ROUTE_RELATION",
            "basis_refs",
            allow_empty=False,
        )
        if relation_kind == "active_node" and subject_ref != active_node:
            raise ArtifactValidationError(
                "SUBJECT_ROUTE_RELATION",
                "active_node relation does not name the active node",
            )
        if relation_kind == "active_path_ancestor" and (
            subject_ref not in active_path[:-1]
        ):
            raise ArtifactValidationError(
                "SUBJECT_ROUTE_RELATION",
                "active_path_ancestor is not an upstream active-path item",
            )
        if relation_kind in {
            "active_path_descendant",
            "inactive_sibling",
            "outside_current_route",
            "unknown",
        } and subject_ref in active_path:
            raise ArtifactValidationError(
                "SUBJECT_ROUTE_RELATION",
                "off-path relation names an active-path item",
            )
    _unique_string_list(
        value["basis_refs"], "NAVIGATION_CONTEXT", "basis_refs", allow_empty=False
    )
    return value


def _validate_project_route_reads(
    value: Any,
    navigation: dict[str, Any],
    required_findings: list[dict[str, Any]],
) -> list[dict[str, str]]:
    if not isinstance(value, list) or not value:
        raise ArtifactValidationError(
            "PROJECT_ROUTE_READS", "project_route_reads must be a non-empty list"
        )
    reads_by_ref: dict[str, dict[str, str]] = {}
    owner_count = 0
    for item in value:
        if not isinstance(item, dict) or set(item) != {"ref", "sha256", "role"}:
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", "project route read has wrong fields"
            )
        ref = _safe_relative_file_ref(item["ref"], "PROJECT_ROUTE_READS", "ref")
        if ref in reads_by_ref:
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", f"duplicate project route read: {ref}"
            )
        if item["role"] not in PROJECT_ROUTE_READ_ROLES:
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", f"unsupported project route role: {ref}"
            )
        if not isinstance(item["sha256"], str) or not SHA256_RE.fullmatch(
            item["sha256"]
        ):
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", f"invalid project route hash: {ref}"
            )
        if item["role"] == "plan_tree_owner":
            owner_count += 1
            if Path(ref).name.casefold() != "project-plan-tree.md":
                raise ArtifactValidationError(
                    "PROJECT_ROUTE_READS",
                    "plan_tree_owner must bind PROJECT-PLAN-TREE.md",
                )
        reads_by_ref[ref] = {"ref": ref, "sha256": item["sha256"], "role": item["role"]}
    if owner_count != 1:
        raise ArtifactValidationError(
            "PROJECT_ROUTE_READS",
            "project_route_reads require exactly one Plan Tree owner",
        )

    navigation_refs = list(navigation["basis_refs"])
    for relation in navigation["subject_route_relations"]:
        navigation_refs.extend(relation["basis_refs"])
    required_by_path: dict[str, set[str]] = {}
    for ref in navigation_refs:
        path = _anchored_ref_path(ref, "PROJECT_ROUTE_READS", "navigation basis ref")
        required_by_path.setdefault(path, set()).add("navigation")
    for finding in required_findings:
        path = _anchored_ref_path(
            finding["ref"], "PROJECT_ROUTE_READS", "authority finding ref"
        )
        required_by_path.setdefault(path, set()).add(finding["kind"])

    if set(reads_by_ref) != set(required_by_path):
        missing = sorted(set(required_by_path) - set(reads_by_ref))
        extra = sorted(set(reads_by_ref) - set(required_by_path))
        raise ArtifactValidationError(
            "PROJECT_ROUTE_READS",
            f"project route reads differ from cited route evidence; missing={missing}, extra={extra}",
        )
    for ref, uses in required_by_path.items():
        role = reads_by_ref[ref]["role"]
        if "navigation" in uses and role not in {"plan_tree_owner", "plan_tree_node"}:
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", f"navigation basis has non-Plan-Tree role: {ref}"
            )
        if "stale_mirror" in uses and role != "route_mirror":
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", f"stale mirror lacks route_mirror bytes: {ref}"
            )
        if "authority_conflict" in uses and role != "peer_owner":
            raise ArtifactValidationError(
                "PROJECT_ROUTE_READS", f"authority conflict lacks peer_owner bytes: {ref}"
            )
    return list(reads_by_ref.values())


def _validate_expected_context(
    receipt: dict[str, Any],
    contract: dict[str, Any],
    expected: dict[str, Any] | None,
) -> None:
    """Bind successor bytes to profile and scope resolved before generation."""
    if expected is None:
        raise ArtifactValidationError(
            "VALIDATION_CONTEXT_REQUIRED",
            "v2 validation requires pre-generation profile and scope expectations",
        )
    if not isinstance(expected, dict) or set(expected) != EXPECTED_CONTEXT_FIELDS:
        raise ArtifactValidationError(
            "VALIDATION_CONTEXT", "expected context has the wrong fields"
        )
    if expected["runtime_profile"] not in RUNTIME_PROFILES:
        raise ArtifactValidationError(
            "VALIDATION_CONTEXT", "expected runtime profile is invalid"
        )
    if expected["runtime_profile_source"] not in RUNTIME_PROFILE_SOURCES:
        raise ArtifactValidationError(
            "VALIDATION_CONTEXT", "expected runtime profile source is invalid"
        )
    affected = _string_list(
        expected["affected_node_refs"],
        "VALIDATION_CONTEXT",
        "affected_node_refs",
        allow_empty=False,
    )
    blocked = _string_list(
        expected["blocked_scope"], "VALIDATION_CONTEXT", "blocked_scope"
    )
    unaffected = _string_list(
        expected["unaffected_scope"], "VALIDATION_CONTEXT", "unaffected_scope"
    )
    if expected["scope_isolation_status"] not in {"proven", "unknown"}:
        raise ArtifactValidationError(
            "VALIDATION_CONTEXT", "expected scope isolation status is invalid"
        )
    if (
        receipt["runtime_profile"] != expected["runtime_profile"]
        or receipt["runtime_profile_source"] != expected["runtime_profile_source"]
    ):
        raise ArtifactValidationError(
            "PROFILE_EXPECTATION_MISMATCH",
            "artifact profile/source differs from the pre-generation selection",
        )
    expected_scope = {
        "affected_node_refs": affected,
        "blocked_scope": blocked,
        "unaffected_scope": unaffected,
        "scope_isolation_status": expected["scope_isolation_status"],
    }
    actual_scope = {
        "affected_node_refs": contract["affected_node_refs"],
        "blocked_scope": contract["blocked_scope"],
        "unaffected_scope": contract["unaffected_scope"],
        "scope_isolation_status": contract["scope_isolation"]["status"],
    }
    if actual_scope != expected_scope:
        raise ArtifactValidationError(
            "SCOPE_EXPECTATION_MISMATCH",
            "artifact scope differs from the pre-generation dependency boundary",
        )


def _validate_ai(contract: dict[str, Any]) -> str:
    """Validate historical v1-v3 or the current v4 AI contract."""
    schema = contract.get("contract_schema")
    if schema == AI_SCHEMA_V1:
        _validate_ai_common(contract, AI_FIELDS_V1, AI_SCHEMA_V1)
        return AI_SCHEMA_V1
    if schema == AI_SCHEMA_V2:
        _validate_ai_common(contract, AI_FIELDS_V2, AI_SCHEMA_V2)
        if contract["runtime_profile"] not in RUNTIME_PROFILES:
            raise ArtifactValidationError(
                "PROFILE_FIELD", "unsupported runtime_profile"
            )
        if contract["runtime_profile_source"] not in RUNTIME_PROFILE_SOURCES:
            raise ArtifactValidationError(
                "PROFILE_SOURCE", "unsupported runtime_profile_source"
            )
        _validate_scope_isolation(contract)
        _validate_owner_precedence(contract)
        return AI_SCHEMA_V2
    if schema == AI_SCHEMA_V3:
        _validate_ai_modern(
            contract,
            schema=AI_SCHEMA_V3,
            fields=AI_FIELDS_V3,
            require_navigation=False,
        )
        return AI_SCHEMA_V3
    if schema == AI_SCHEMA:
        _validate_ai_modern(
            contract,
            schema=AI_SCHEMA,
            fields=AI_FIELDS_V4,
            require_navigation=True,
        )
        return AI_SCHEMA
    raise ArtifactValidationError("AI_SCHEMA", "unsupported contract_schema")


def _validate_ai_modern(
    contract: dict[str, Any],
    *,
    schema: str,
    fields: set[str],
    require_navigation: bool,
) -> None:
    if set(contract) != fields:
        missing = sorted(fields - set(contract))
        extra = sorted(set(contract) - fields)
        raise ArtifactValidationError("AI_SCHEMA", f"missing={missing}, extra={extra}")
    if contract["contract_schema"] != schema:
        raise ArtifactValidationError("AI_SCHEMA", "unsupported contract_schema")
    for field in (
        "contract_id",
        "artifact_producer_id",
        "revision_id",
        "subject",
        "provenance",
        "authority",
        "freshness",
        "time_range",
        "readiness",
    ):
        _nonempty(contract[field], "AI_FIELD", field)
    projections = _assert_projection_refs(
        contract["projection_refs"], "AI_PROJECTION_REFS"
    )
    entity = _validate_entity(contract["understanding_entity"])
    if (
        entity["identity_status"] == "provisional"
        and contract["authority"] != "candidate"
    ):
        raise ArtifactValidationError(
            "ENTITY_IDENTITY", "provisional entity must remain candidate"
        )
    _validate_working_refs(contract["working_refs"], projections)
    _validate_operation_context(contract["operation_context"])
    _unique_string_list(contract["read_scope_refs"], "READ_SCOPE", "read_scope_refs")
    _unique_string_list(
        contract["evidence_scope_refs"], "EVIDENCE_SCOPE", "evidence_scope_refs"
    )
    _validate_impact_scope(contract["impact_scope"])
    _validate_route_permission(
        contract["route_permission"],
        contract["operation_context"],
        contract["impact_scope"],
    )
    _validate_unknowns(
        contract["unknowns"], entity["entity_id"], contract["impact_scope"]
    )
    _unique_string_list(
        contract["invalidation_conditions"],
        "AI_FIELD",
        "invalidation_conditions",
    )
    if contract["runtime_profile"] not in RUNTIME_PROFILES:
        raise ArtifactValidationError("PROFILE_FIELD", "unsupported runtime_profile")
    if contract["runtime_profile_source"] not in RUNTIME_PROFILE_SOURCES:
        raise ArtifactValidationError(
            "PROFILE_SOURCE", "unsupported runtime_profile_source"
        )
    _validate_owner_precedence(contract)
    if require_navigation:
        _validate_navigation_context(contract["navigation_context"])
    for name in _walk_names(contract):
        if name in FORBIDDEN_NAMES:
            raise ArtifactValidationError(
                "AI_FORBIDDEN_BODY", f"forbidden field: {name}"
            )
    encoded = json.dumps(
        contract, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    if len(encoded) > MAX_AI_BYTES:
        raise ArtifactValidationError(
            "AI_TOO_LARGE", f"normalized contract is {len(encoded)} bytes"
        )
    serialized = json.dumps(contract, ensure_ascii=False)
    if any(label in serialized for label in FORBIDDEN_LABELS):
        raise ArtifactValidationError(
            "PROJECTION_CANONICAL_LABEL_FORBIDDEN", "canonical projection label"
        )


def _validate_context_owner(
    value: Any,
    *,
    expected_owner: str,
    expected_ref: str,
    code: str,
    require_provenance: bool,
) -> None:
    fields = {"owner", "owner_ref", "owner_sha256"}
    if require_provenance:
        fields.add("provenance")
    else:
        fields.add("basis_refs")
    if not isinstance(value, dict) or set(value) != fields:
        raise ArtifactValidationError(code, "context owner has wrong fields")
    if value["owner"] != expected_owner or value["owner_ref"] != expected_ref:
        raise ArtifactValidationError(code, "context owner identity differs")
    if not isinstance(value["owner_sha256"], str) or not SHA256_RE.fullmatch(
        value["owner_sha256"]
    ):
        raise ArtifactValidationError(code, "context owner hash is invalid")
    if require_provenance:
        if value["provenance"] != "owner_derived_before_generation":
            raise ArtifactValidationError(code, "oracle provenance is invalid")
    else:
        _unique_string_list(value["basis_refs"], code, "basis_refs", allow_empty=False)


def _validate_generation_context(context: dict[str, Any]) -> str:
    schema = context.get("context_schema")
    if schema == GENERATION_CONTEXT_SCHEMA_V1:
        fields = GENERATION_CONTEXT_FIELDS
    elif schema == GENERATION_CONTEXT_SCHEMA:
        fields = GENERATION_CONTEXT_FIELDS_V2
    else:
        raise ArtifactValidationError(
            "GENERATION_CONTEXT_SCHEMA", "unsupported generation context schema"
        )
    if set(context) != fields:
        missing = sorted(fields - set(context))
        extra = sorted(set(context) - fields)
        raise ArtifactValidationError(
            "GENERATION_CONTEXT_SCHEMA", f"missing={missing}, extra={extra}"
        )
    _nonempty(context["context_id"], "GENERATION_CONTEXT", "context_id")
    entity = _validate_entity(context["understanding_entity"])
    _nonempty(context["revision_id"], "GENERATION_CONTEXT", "revision_id")
    _validate_context_owner(
        context["oracle_owner"],
        expected_owner="project_intelligence",
        expected_ref="project-intelligence.md",
        code="GENERATION_CONTEXT_OWNER",
        require_provenance=True,
    )
    _validate_context_owner(
        context["dependency_owner"],
        expected_owner="plan_tree",
        expected_ref="plan-tree.md",
        code="GENERATION_CONTEXT_OWNER",
        require_provenance=False,
    )
    oracle_producer = _nonempty(
        context["oracle_producer_id"], "GENERATION_CONTEXT", "oracle_producer_id"
    )
    artifact_producer = _nonempty(
        context["artifact_producer_id"],
        "GENERATION_CONTEXT",
        "artifact_producer_id",
    )
    if oracle_producer == artifact_producer:
        raise ArtifactValidationError(
            "ORACLE_PRODUCER_NOT_SEPARATE",
            "scope oracle and artifact producer identities must differ",
        )
    if context["runtime_profile"] not in RUNTIME_PROFILES:
        raise ArtifactValidationError("PROFILE_FIELD", "unsupported runtime_profile")
    if context["runtime_profile_source"] not in RUNTIME_PROFILE_SOURCES:
        raise ArtifactValidationError(
            "PROFILE_SOURCE", "unsupported runtime_profile_source"
        )
    _validate_operation_context(context["operation_context"])
    _unique_string_list(context["read_scope_refs"], "READ_SCOPE", "read_scope_refs")
    _unique_string_list(
        context["evidence_scope_refs"], "EVIDENCE_SCOPE", "evidence_scope_refs"
    )
    _validate_impact_scope(context["impact_scope"])
    _validate_route_permission(
        context["route_permission"],
        context["operation_context"],
        context["impact_scope"],
    )
    _validate_unknowns(
        context["required_unknowns"],
        entity["entity_id"],
        context["impact_scope"],
    )
    if schema == GENERATION_CONTEXT_SCHEMA:
        navigation = _validate_navigation_context(context["navigation_context"])
        findings = _validate_authority_findings(
            context["required_authority_findings"],
            required_route_findings=True,
        )
        if context["dependency_owner"]["basis_refs"] != navigation["basis_refs"]:
            raise ArtifactValidationError(
                "NAVIGATION_OWNER_BINDING",
                "Plan Tree dependency basis differs from navigation basis refs",
            )
        _validate_project_route_reads(
            context["project_route_reads"], navigation, findings
        )
    return schema


def _validate_context_binding(
    receipt: dict[str, Any], contract: dict[str, Any], context: dict[str, Any]
) -> None:
    expected = {
        "artifact_producer_id": context["artifact_producer_id"],
        "understanding_entity": context["understanding_entity"],
        "revision_id": context["revision_id"],
        "runtime_profile": context["runtime_profile"],
        "runtime_profile_source": context["runtime_profile_source"],
        "operation_context": context["operation_context"],
        "read_scope_refs": context["read_scope_refs"],
        "evidence_scope_refs": context["evidence_scope_refs"],
        "impact_scope": context["impact_scope"],
        "route_permission": context["route_permission"],
    }
    if context["context_schema"] == GENERATION_CONTEXT_SCHEMA:
        expected["navigation_context"] = context["navigation_context"]
    actual = {key: contract[key] for key in expected}
    if actual != expected:
        raise ArtifactValidationError(
            "GENERATION_CONTEXT_MISMATCH",
            "AI contract differs from the frozen generation context",
        )
    actual_unknowns = {item["unknown_id"]: item for item in contract["unknowns"]}
    for required in context["required_unknowns"]:
        if actual_unknowns.get(required["unknown_id"]) != required:
            raise ArtifactValidationError(
                "REQUIRED_UNKNOWN_MISMATCH",
                f"required unknown differs: {required['unknown_id']}",
            )
    if context["context_schema"] == GENERATION_CONTEXT_SCHEMA:
        actual_findings = {
            (
                item["kind"],
                item["ref"],
                item["owner"],
                item["disposition"],
            )
            for item in contract["authority_findings"]
        }
        for required in context["required_authority_findings"]:
            identity = (
                required["kind"],
                required["ref"],
                required["owner"],
                required["disposition"],
            )
            if identity not in actual_findings:
                raise ArtifactValidationError(
                    "REQUIRED_AUTHORITY_FINDING_MISMATCH",
                    f"required authority finding differs: {required['ref']}",
                )
    if receipt["artifact_producer_id"] != context["artifact_producer_id"]:
        raise ArtifactValidationError(
            "GENERATION_CONTEXT_MISMATCH", "receipt producer differs from context"
        )


